<?php
/**
 * =====================================================================================
 * 【ファイル名】 TaskPolicy.php
 * 【アーキテクチャ上の位置づけ】 認可層（セキュリティポリシー / アクセスコントロール）
 * =====================================================================================
 * 【実務における設計思想】
 * マルチユーザー環境における厳格なデータ所有権の検証とアクセス制御を担当します。
 * Laravelのポリシー機構を活用し、認証済みユーザーが他者のタスクに対して不正に
 * アクセス（閲覧・更新・削除）することを防ぐためのセキュリティ境界を定義します。
 * コントローラー側での $this->authorize() 呼び出しと密に連携し、
 * アプリケーション全体の安全性を担保する中核的な役割を果たします。
 */
namespace App\Policies;

use App\Models\Task;
use App\Models\User;

class TaskPolicy
{
    /**
     * =====================================================================================
     * 【メソッド名】 viewAny
     * 【概要】 タスク一覧の閲覧権限判定処理
     * =====================================================================================
     * ユーザーがタスクの一覧画面（または全件）を閲覧する権限を持つか判定します。
     * 実際の絞り込みはコントローラー側のクエリスコープで行うため、認証済みであれば許可します。
     *
     * @param User $user 認証済みのユーザーモデル
     * @return bool 閲覧を許可する場合は true
     */
    public function viewAny(User $user): bool
    {
        return true;
    }

    /**
     * =====================================================================================
     * 【メソッド名】 view
     * 【概要】 特定タスクの詳細閲覧権限判定処理
     * =====================================================================================
     * ユーザーが特定のタスクの詳細を閲覧する権限を持つか判定します。
     * ログインユーザーのIDとタスクの所有者IDが完全に一致する場合のみ許可します。
     *
     * @param User $user 認証済みのユーザーモデル
     * @param Task $task 対象のタスクモデル
     * @return bool 所有者本人の場合は true、それ以外は false
     */
    public function view(User $user, Task $task): bool
    {
        return $user->id === $task->user_id;
    }

    /**
     * =====================================================================================
     * 【メソッド名】 create
     * 【概要】 タスク作成権限判定処理
     * =====================================================================================
     * ユーザーが新規タスクを作成する権限を持つか判定します。
     * 認証済みのユーザーであれば誰でもタスクの作成を許可します。
     *
     * @param User $user 認証済みのユーザーモデル
     * @return bool 作成を許可する場合は true
     */
    public function create(User $user): bool
    {
        return true;
    }

    /**
     * =====================================================================================
     * 【メソッド名】 update
     * 【概要】 タスク更新権限判定処理
     * =====================================================================================
     * ユーザーが特定のタスクを更新する権限を持つか判定します。
     * 所有者本人（$user->id === $task->user_id）である場合のみ更新を許可し、他人の改変を厳格に防止します。
     *
     * @param User $user 認証済みのユーザーモデル
     * @param Task $task 対象のタスクモデル
     * @return bool 所有者本人の場合は true、それ以外は false
     */
    public function update(User $user, Task $task): bool
    {
        return $user->id === $task->user_id;
    }

    /**
     * =====================================================================================
     * 【メソッド名】 delete
     * 【概要】 タスク削除権限判定処理
     * =====================================================================================
     * ユーザーが特定のタスクを削除する権限を持つか判定します。
     * 所有者本人（$user->id === $task->user_id）である場合のみ削除を許可し、他人の不正削除を厳格に防止します。
     *
     * @param User $user 認証済みのユーザーモデル
     * @param Task $task 対象のタスクモデル
     * @return bool 所有者本人の場合は true、それ以外は false
     */
    public function delete(User $user, Task $task): bool
    {
        return $user->id === $task->user_id;
    }
}